#ifndef POISGEN2_H
#define POISGEN2_H

#include "poisgen.h"

/**
 * @brief Класс-генератор пуассоновских случайных величин на основе связи с экспоненциальным распределением.
 * @details Реализует классический алгоритм Кнута для моделирования пуассоновского распределения.
 * Физический смысл алгоритма заключается в подсчете количества событий простейшего (пуассоновского) потока,
 * произошедших за единицу времени, где интервалы между событиями распределены экспоненциально.
 * Математически это выражается через произведение независимых равномерных величин: цикл продолжается,
 * пока произведение случайных чисел \f$U_1 \cdot U_2 \cdot \dots \cdot U_n\f$ остается больше или равно \f$e^{-\lambda}\f$.
 * * @note Метод не требует предварительного вычисления таблиц вероятностей (кэша), однако при больших значениях
 * \f$\lambda\f$ (обычно \f$\lambda > 30\f$) возникает проблема машинного недозаряда (underflow), так как \f$e^{-\lambda}\f$
 * становится критически близко к нулю. Также для больших \f$\lambda\f$ метод становится медленным из-за большого числа умножений.
 */
class PoisGen2 : public PoisGen
{
public:
    /**
     * @brief Конструктор генератора PoisGen2.
     * @details Перенаправляет параметры в конструктор базового класса PoisGen.
     * @param dist Указатель на объект теоретического распределения с параметрами.
     * @param stdgen Указатель на внешний движок генерации псевдослучайных чисел.
     */
    PoisGen2(Distribution *dist, std::mt19937_64* stdgen):
        PoisGen(dist, stdgen){}

    /**
     * @brief Моделирует и возвращает одно случайное значение распределения Пуассона.
     * @details Использует итеративное умножение случайных чисел из диапазона `[0, 1)`
     * и сравнение накопленного произведения с пороговым значением \f$e^{-\lambda}\f$.
     * * @return int Сгенерированное случайное пуассоновское число \f$n \ge 0\f$.
     */
    int gen();
};

#endif // POISGEN2_H
