#ifndef DISTRIBUTION_H
#define DISTRIBUTION_H

#include <cmath>

/**
 * @brief Класс для расчета и хранения теоретических вероятностей распределения Пуассона.
 * @details Класс автоматически вычисляет и кэширует значения вероятностей (PMF)
 * и кумулятивных сумм (CDF) распределения Пуассона для оптимизации повторных запросов.
 */
class Distribution
{
private:
    double _lambda; ///< Параметр интенсивности (лямбда) распределения Пуассона.
public:
    double *_computed_probs; ///< Динамический массив для кэшированных индивидуальных вероятностей P(X = k).
    double *_computed_cumsums; ///< Динамический массив для кэшированных кумулятивных вероятностей P(X <= k).
    int _n_computed; ///< Количество уже вычисленных элементов в кэш-массивах.
    int _capacity; ///< Текущий зарезервированный размер выделенной памяти под массивы.

    /**
     * @brief Конструктор, инициализирующий распределение с заданной интенсивностью.
     * @param lambda Значение параметра лямбда (должно быть строго больше 0).
     */
    Distribution(double lambda);

    Distribution(const Distribution& other);
    Distribution(Distribution&& other);
    Distribution& operator=(const Distribution& other);

    /**
     * @brief Деструктор класса. Освобождает выделенную динамическую память под массивы кэша.
     */
    ~Distribution();

    /**
     * @brief Получить текущее значение параметра лямбда.
     * @return double Значение интенсивности распределения.
     */
    double get_lambda() const;

    /**
     * @brief Расширить кэш вычисленных вероятностей до указанного индекса.
     * @details Если запрашиваемый индекс превышает текущую емкость кэша,
     * память автоматически перевыделяется (стратегия удвоения емкости).
     * @param compute_up_to Индекс, до которого необходимо гарантировать расчет вероятностей.
     */
    void update_probs(int compute_up_to);

    /**
     * @brief Заполнить внешний массив значениями вероятностей до определенной правой границы.
     * @param right_lim Правая граница распределения (количество состояний).
     * @param p Указатель на выделенный внешний массив, куда будут скопированы данные.
     */
    void get_probs(int right_lim, double *p);

    /**
     * @brief Идентификатор класса.
     * @return const char* Возвращает текстовую строку с именем класса или распределения.
     */
    const char* whoami() const;
};

#endif // DISTRIBUTION_H
