#ifndef CHISQ_H
#define CHISQ_H

#include "probdist.h"
#include "poisgen.h"

/**
 * @brief Пороговое значение для объединения малочисленных интервалов.
 * @details Согласно критерию Пирсона (Хи-квадрат), ожидаемая частота в группе
 * должна быть не менее 5.0 для корректной работы аппроксимации.
 */
const double CUM_EXP_FREQ_THRESH = 5.0;

/**
 * @brief Класс для проведения статистического анализа соответствия критерию Хи-квадрат Пирсона.
 * @details Рассчитывает эмпирические и теоретические частоты на основе выборки генератора
 * и проверяет нулевую гипотезу о соответствии пуассоновскому распределению.
 */
class ChiSq
{
private:
    /**
     * @brief Внутренний метод для расчета итоговой статистики Хи-квадрат.
     * @details Выполняет агрегацию частот, если теоретическое значение меньше порога CUM_EXP_FREQ_THRESH.
     * @return double Значение вычисленной статистики критерия.
     */
    double compute_chisq_stat();

    /**
     * @brief Определяет оптимальное количество интервалов группировки (состояний).
     * @param sample_size Размер анализируемой выборки.
     * @param dist Ссылка на теоретическое распределение.
     * @return int Количество результирующих групп.
     */
    int get_lim(int sample_size, Distribution *dist);

    /**
     * @brief Подсчитывает наблюдаемые частоты по выборке и формирует массив теоретических частот.
     * @param p Массив теоретических вероятностей.
     * @param gen Указатель на генератор, содержащий сгенерированную выборку.
     */
    void compute_freqs(double *p, PoisGen *gen);
public:
    double _pval; ///< Вычисленное значение p-value для полученной статистики.
    double _stat; ///< Итоговое эмпирическое значение статистики Хи-квадрат.
    int _df; ///< Число степеней свободы (degrees of freedom) для распределения критерия.
    int _n_states; ///< Исходное количество анализируемых состояний (интервалов) до объединения.
    double *_exp_freqs; ///< Массив теоретических (ожидаемых) частот для каждого состояния.
    double *_obs_freqs; ///< Массив эмпирических (фактически наблюдавшихся) частот по выборке.

    /**
     * @brief Конструктор, запускающий полный цикл анализа Хи-квадрат для генератора.
     * @param gen Указатель на генератор случайных величин с готовой выборкой.
     * @param d0 Указатель на гипотетическое (теоретическое) распределение.
     */
    ChiSq(PoisGen *gen, Distribution *d0);
    ChiSq(const ChiSq& other);
    ChiSq(ChiSq&& other);
    ChiSq& operator=(const ChiSq& other);
    ChiSq& operator=(ChiSq&& other);

    /**
     * @brief Пересчитать критерий Хи-квадрат для новой выборки или нового распределения.
     * @details Перевыделяет внутреннюю память под частоты и перезапускает вычисления.
     * @param gen Указатель на генератор с новой выборкой.
     * @param d0 Указатель на теоретическое распределение.
     */
    void set_sample(PoisGen *gen, Distribution *d0);

    /**
     * @brief Деструктор класса. Освобождает массивы частот _exp_freqs и _obs_freqs.
     */
    ~ChiSq();
};

#endif // CHISQ_H
