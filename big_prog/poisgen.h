#ifndef POISGEN_H
#define POISGEN_H
#include <random>
#include "distribution.h"


/**
 * @brief Абстрактный базовый класс для генераторов случайных величин, распределенных по Пуассону.
 * @details Определяет общий интерфейс генерации единичных значений и накопления массивов выборок.
 * Объекты `_dist` и `_stdgen` являются внешними ресурсами и не уничтожаются данным классом.
 */
class PoisGen
{
protected:
    Distribution *_dist; ///< Указатель на объект распределения с параметрами.
    std::mt19937_64* _stdgen; ///< Указатель на базовый внешний движок генерации псевдослучайных чисел (Mersenne Twister).

public:
    double _lambda; ///< Скопированное значение интенсивности распределения (для быстрого доступа).
    int _min_val; ///< Минимальное значение, зафиксированное в сгенерированной выборке.
    int _max_val; ///< Максимальное значение, зафиксированное в сгенерированной выборке.
    int _sample_size; ///< Текущий размер сгенерированной выборки.
    int* _sample; ///< Динамический массив, хранящий элементы сгенерированной выборки.

    /**
     * @brief Конструктор базового генератора.
     * @param dist Внешний объект распределения.
     * @param stdgen Внешний генератор базовых случайных чисел.
     */
    PoisGen(Distribution* dist, std::mt19937_64* stdgen);
    PoisGen(const PoisGen& other);
    PoisGen(PoisGen&& other);
    PoisGen& operator=(const PoisGen& other);

    /**
     * @brief Виртуальный деструктор. Гарантирует безопасную очистку памяти массива `_sample`
     * при уничтожении объектов через указатель на базовый класс.
     */
    virtual ~PoisGen();

    /**
     * @brief Сгенерировать и сохранить выборку случайных величин заданного размера.
     * @details Метод автоматически очищает старую выборку, выделяет новую память,
     * заполняет её с помощью вызовов виртуальной функции gen() и фиксирует минимумы/максимумы.
     * @param n Требуемый размер выборки.
     */
    void gen_sample(int n);

    /**
     * @brief Чистая виртуальная функция для генерации одного случайного значения.
     * @details Должна быть переопределена в конкретных классах-наследниках (например, PoisGen1, PoisGen2)
     * с реализацией конкретного алгоритма моделирования (метод трансформации, метод обратных функций и т.д.).
     * @return int Сгенерированное случайное число.
     */
    virtual int gen() = 0;

};

#endif // POISGEN_H
